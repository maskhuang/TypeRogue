// ─── 5. MIB Lexicon ───

function extractMibLexicon() {
  // Signal-word dictionary (v3.1 renamed: MIB → 收容; v3.0 fallback for compat)
  const dictSlice =
    sliceFromHeading(doc, /^### 收容信号词词典.*$/m, '^### |^## ') ||
    sliceFromHeading(doc, /^### MIB 信号词词典.*$/m, '^### |^## ')
  const dictRows = parseMdTable(findFirstTable(dictSlice))
  const signal = []
  for (const row of dictRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    // v3.1 has a new "#" column at index 0; detect and shift
    const hasNumColumn = keys[0] === '#' || /^[#🟢]/.test(keys[0]) || /^\d+$/.test(row[keys[0]] || '')
    const off = hasNumColumn ? 1 : 0
    const type = row[keys[off]]; const examples = row[keys[off + 1]]; const hint = row[keys[off + 2]]
    if (type && type !== '信号词类型' && type !== '信号子类') {
      signal.push({
        type: type.replace(/^🟢\s*\d+\s*\|\s*/, '').replace(/（v3\.1[^）]*）/g, '').trim(),
        examples: (examples || '').split(/[、，,]/).map(s => s.replace(/^"|"$/g, '').trim()).filter(Boolean),
        hint: hint || '',
      })
    }
  }

  // Calibration sample (first ``` block under "## MIB 风格校准锚")
  const sampleSec = sliceFromHeading(doc, /^## MIB 风格校准锚.*$/m, '^## ')
  const sampleMatch = sampleSec.match(/```\n([\s\S]*?)\n```/)
  const calibrationSample = sampleMatch ? sampleMatch[1].trim() : ''

  // Implementation rules (v3.1 renamed: MIB → 收容主义官僚; v3.0 fallback)
  const ruleSlice =
    sliceFromHeading(doc, /^### 收容主义官僚 · 实施铁律.*$/m, '^### |^## ') ||
    sliceFromHeading(doc, /^### MIB 风格的实施铁律.*$/m, '^### |^## ')
  const rules = ruleSlice.split('\n')
    .filter(l => /^\s*-\s+(✅|❌)/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())

  return {
    signal,
    rules,
    calibration_sample: calibrationSample,
    density_rule: '每段 flavor 都暗示水底，但永远不下水。',
    naming_note: 'v3.1: MIB 风格 → 收容主义官僚（不命名 SCP / 玩家文本中永远不出现"收容/异常 entity/Foundation/SCP/object class"等术语）',
  }
}

// ─── 7. Affix Taxa (v3.1 NEW) — 59 base 词缀 NCBI 学名映射 ───

function extractAffixTaxa() {
  const sec = sliceFromHeading(
    doc,
    /^## 🟢 Step 4\.5 \(v3\.1 NEW\) · 词缀编码体系.*$/m,
    '^## '
  )

  // Each category has a #### sub-heading with a single table.
  // Categories: Numeric / Crit / Stack / Topology / Word Sense / Meta Rule / Production
  const categories = [
    { id: 'numeric',    re: /^#### Numeric \(\d+\).*$/m },
    { id: 'crit',       re: /^#### Crit \(\d+\).*$/m },
    { id: 'stack',      re: /^#### Stack \(\d+\).*$/m },
    { id: 'topology',   re: /^#### Topology \(\d+\).*$/m },
    { id: 'word_sense', re: /^#### Word Sense \(\d+\).*$/m },
    { id: 'meta_rule',  re: /^#### Meta Rule \(\d+\).*$/m },
    { id: 'production', re: /^#### Production \(\d+\).*$/m },
  ]

  const out = {}
  for (const def of categories) {
    const slice = sliceFromHeading(sec, def.re, '^#### |^### |^## ')
    const tableSrc = findFirstTable(slice)
    if (!tableSrc) continue
    const rows = parseMdTable(tableSrc)
    out[def.id] = rows.map(row => {
      const keys = Object.keys(row)
      if (keys.length < 4) return null
      // Columns: 词缀 | 代码 | 拉丁名 | 中文
      const affix = row[keys[0]]
      const code = row[keys[1]]
      const latin = stripBold(row[keys[2]] || '').replace(/^\*|\*$/g, '').trim()
      const common_zh = row[keys[3]]
      if (!affix || affix === '词缀') return null
      return {
        affix,
        code,
        latin: latin.replace(/^\*+|\*+$/g, '').trim(),
        common_zh,
        taxid: null, // TBD: NCBI taxonomy ID lookup at production time
      }
    }).filter(Boolean)
  }

  // Flatten lookup for validators
  const all = Object.entries(out).flatMap(([cat, items]) =>
    items.map(item => ({ ...item, category: cat }))
  )

  return { by_category: out, all, total: all.length }
}

