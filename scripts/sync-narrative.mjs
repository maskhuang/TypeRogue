// ─── Markdown utilities ───

function parseMdTable(text) {
  const lines = text.trim().split('\n').filter(l => l.trim().startsWith('|'))
  if (lines.length < 2) return []
  const headers = splitRow(lines[0])
  const rows = []
  for (let i = 2; i < lines.length; i++) {
    const cells = splitRow(lines[i])
    if (cells.length < headers.length) continue
    const row = {}
    headers.forEach((h, j) => { row[h] = stripBold(cells[j] || '') })
    rows.push(row)
  }
  return rows
}

function splitRow(line) {
  // Markdown table row: | a | b | c |
  return line.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim())
}

function stripBold(s) {
  return s.replace(/\*\*/g, '').trim()
}

// Split on comma, but ignore commas inside parentheses
function splitCommaPreserveParens(s) {
  const out = []
  let depth = 0
  let buf = ''
  for (const ch of s) {
    if (ch === '(') depth++
    else if (ch === ')') depth = Math.max(0, depth - 1)
    if (ch === ',' && depth === 0) {
      if (buf.trim()) out.push(buf.trim())
      buf = ''
    } else {
      buf += ch
    }
  }
  if (buf.trim()) out.push(buf.trim())
  return out
}

// Slice doc from a starting heading (regex) up to next heading at the same-or-shallower level
function sliceFromHeading(md, headingRegex, stopHeadingPattern = '^##? ') {
  const m = md.match(headingRegex)
  if (!m) return ''
  const start = m.index + m[0].length
  const after = md.slice(start)
  const stopRe = new RegExp(stopHeadingPattern, 'm')
  const stop = after.match(stopRe)
  return stop ? after.slice(0, stop.index) : after
}

function findFirstTable(text) {
  const m = text.match(/(\|[^\n]+\|\s*\n\|[-|:\s]+\|\s*\n(?:\|[^\n]+\|\s*\n?)+)/)
  return m ? m[1] : ''
}

function findAllTables(text) {
  const re = /(\|[^\n]+\|\s*\n\|[-|:\s]+\|\s*\n(?:\|[^\n]+\|\s*\n?)+)/g
  const out = []
  let m
  while ((m = re.exec(text)) !== null) out.push(m[1])
  return out
}

// ─── 1. Anchor Facts (Step 4) ───

function extractAnchorFacts() {
  const step4 = sliceFromHeading(doc, /^## Step 4 · Character Anchors.*$/m, '^## Step 5')
  const anchors = {}

  // Single-table anchors: heading regex → output id
  const singleTableAnchors = [
    { id: 'player',     re: /^### Anchor 1 · #485,902.*$/m, label: '玩家 · #485,902' },
    { id: 'superior',   re: /^### Anchor 2 · 上级权威.*$/m, label: '上级权威（A 主任 + B 月度考核官）' },
    { id: 'hr',         re: /^### Anchor 4 · HR.*$/m,       label: 'HR（无形）' },
    { id: 'instructor', re: /^### Anchor 5 · 内训讲师.*$/m, label: '内训讲师' },
  ]

  for (const def of singleTableAnchors) {
    const section = sliceFromHeading(step4, def.re, '^### |^## ')
    const tableSrc = findFirstTable(section)
    if (!tableSrc) continue
    const rows = parseMdTable(tableSrc)
    const facts = { _label: def.label }
    for (const row of rows) {
      const keys = Object.keys(row)
      if (keys.length < 2) continue
      const k = row[keys[0]]
      const v = row[keys[1]]
      if (k && k !== '项' && v) facts[k] = v
    }
    if (Object.keys(facts).length > 1) anchors[def.id] = facts
  }

  // Anchor 3 has two sub-tables (集体层 / 子锚 #485,901)
  const a3section = sliceFromHeading(step4, /^### Anchor 3 · 同事们.*$/m, '^### |^## ')

  const collectiveSlice = sliceFromHeading(a3section, /^#### 集体层.*$/m, '^#### |^### |^## ')
  const collectiveTable = findFirstTable(collectiveSlice)
  if (collectiveTable) {
    const facts = { _label: '同事们 · 集体' }
    for (const row of parseMdTable(collectiveTable)) {
      const keys = Object.keys(row)
      if (keys.length < 2) continue
      const k = row[keys[0]]; const v = row[keys[1]]
      if (k && k !== '项' && v) facts[k] = v
    }
    anchors.peers_collective = facts
  }

  const subSlice = sliceFromHeading(a3section, /^#### 子锚 #485,901.*$/m, '^#### |^### |^## ')
  const subTable = findFirstTable(subSlice)
  if (subTable) {
    const facts = { _label: '#485,901（具名同事 · 子锚）' }
    let lastKey = null
    for (const row of parseMdTable(subTable)) {
      const keys = Object.keys(row)
      if (keys.length < 2) continue
      const k = row[keys[0]]; const v = row[keys[1]]
      if (k === '项' || (!k && !v)) continue
      if (k) {
        facts[k] = v
        lastKey = k
      } else if (lastKey && v) {
        // Continuation row (multi-line value): append
        facts[lastKey] = `${facts[lastKey]}\n${v}`
      }
    }
    anchors.peer_485901 = facts
  }

  return anchors
}

// ─── 2. Translation Table (from Mechanic Hooks + Class Mapping) ───

function extractTranslationTable() {
  const out = []

  // Class Narrative Mapping
  const classSection = sliceFromHeading(doc, /^### Class Narrative Mapping.*$/m, '^### |^## ')
  const classTable = findFirstTable(classSection)
  if (classTable) {
    for (const row of parseMdTable(classTable)) {
      const keys = Object.keys(row)
      if (keys.length < 2) continue
      const game = row[keys[0]]
      const zh = row[keys[1]]
      if (game && zh && game !== '职业（机制）') out.push({ game, zh, en: '' })
    }
  }

  // Mechanic-to-Narrative Hooks
  const hooksSection = sliceFromHeading(doc, /^### Mechanic-to-Narrative Hooks.*$/m, '^### |^## ')
  const hooksTable = findFirstTable(hooksSection)
  if (hooksTable) {
    for (const row of parseMdTable(hooksTable)) {
      const keys = Object.keys(row)
      if (keys.length < 2) continue
      const game = row[keys[0]]
      const zh = row[keys[1]]
      if (game && zh && game !== '机制') out.push({ game, zh, en: '' })
    }
  }

  return out
}

// ─── 3. Stage Config (Acts + Cycles, replaces 12-layer) ───

function extractStageConfig() {
  const config = { acts: [], cycles: [] }

  // Single-Run Act Breakdown
  const actSection = sliceFromHeading(doc, /^### Single-Run Act Breakdown.*$/m, '^### |^## ')
  const actTable = findFirstTable(actSection)
  if (actTable) {
    let currentAct = ''
    for (const row of parseMdTable(actTable)) {
      const keys = Object.keys(row)
      if (keys.length < 4) continue
      const act = row[keys[0]] || currentAct
      const stages = row[keys[1]]
      const semantic = row[keys[2]]
      const density = row[keys[3]]
      if (act) currentAct = act
      if (stages && semantic) config.acts.push({ act: currentAct, stages, semantic, density })
    }
  }

  // Multi-Cycle Career Arc
  const cycleSection = sliceFromHeading(doc, /^### Multi-Cycle Career Arc.*$/m, '^### |^## ')
  const cycleTable = findFirstTable(cycleSection)
  if (cycleTable) {
    for (const row of parseMdTable(cycleTable)) {
      const keys = Object.keys(row)
      if (keys.length < 4) continue
      const cycle = row[keys[0]]
      const stage = row[keys[1]]
      const unlock = row[keys[2]]
      const hook = row[keys[3]]
      if (cycle && cycle !== 'Cycle' && stage) config.cycles.push({ cycle, stage, unlock, hook })
    }
  }

  return config
}

// ─── 4. B1.a Vocab Table (zh + en) ───

function extractB1aVocab() {
  // Locate the section "## B1.a 词汇表" which contains both zh and en sub-sections
  const sec = sliceFromHeading(doc, /^## B1.a 词汇表.*$/m, '^## ')

  return {
    zh: parseB1aZh(sec),
    en: parseB1aEn(sec),
  }
}

function parseB1aZh(sec) {
  // ✅ allowed table under "### ✅ 允许词"
  const allowedSlice = sliceFromHeading(sec, /^### ✅ 允许词.*$/m, '^### |^## ')
  const allowedRows = parseMdTable(findFirstTable(allowedSlice))
  const allowed = {}
  for (const row of allowedRows) {
    const keys = Object.keys(row)
    if (keys.length < 2) continue
    const cat = row[keys[0]]; const words = row[keys[1]]
    if (cat && cat !== '类别' && words) {
      allowed[cat] = words.split(/[、，,]/).map(s => s.trim()).filter(Boolean)
    }
  }

  // ❌ forbidden table
  const forbiddenSlice = sliceFromHeading(sec, /^### ❌ 禁止词.*$/m, '^### |^## ')
  const forbiddenRows = parseMdTable(findFirstTable(forbiddenSlice))
  const forbidden = {}
  for (const row of forbiddenRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    const cat = row[keys[0]]; const words = row[keys[1]]; const reason = row[keys[2]]
    if (cat && cat !== '类别' && words) {
      // Words may contain parenthetical clarifications like "研究（孤用）"
      const list = words.split(/[、，,]/).map(s => s.trim()).filter(Boolean)
      forbidden[cat] = { words: list, reason: reason || '' }
    }
  }

  // ⚠️ context-sensitive table
  const ctxSlice = sliceFromHeading(sec, /^### ⚠️ 上下文敏感词.*$/m, '^### |^## ')
  const ctxRows = parseMdTable(findFirstTable(ctxSlice))
  const contextSensitive = []
  for (const row of ctxRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    const word = row[keys[0]]; const safe = row[keys[1]]; const dangerous = row[keys[2]]
    if (word && word !== '词') contextSensitive.push({ word, safe, dangerous })
  }

  return { allowed, forbidden, contextSensitive }
}

function parseB1aEn(sec) {
  // English sub-section starts with "### B1.a 词汇表 · English Reference"
  const enSlice = sliceFromHeading(sec, /^### B1\.a 词汇表 · English Reference.*$/m, '^### |^## ')

  // #### ✅ Allowed
  const allowedSlice = sliceFromHeading(enSlice, /^#### ✅ Allowed.*$/m, '^#### |^### |^## ')
  const allowedRows = parseMdTable(findFirstTable(allowedSlice))
  const allowed = {}
  for (const row of allowedRows) {
    const keys = Object.keys(row)
    if (keys.length < 2) continue
    const cat = row[keys[0]]; const words = row[keys[1]]
    if (cat && cat !== 'Category' && words) {
      allowed[cat] = splitCommaPreserveParens(words)
    }
  }

  // #### ❌ Forbidden
  const forbiddenSlice = sliceFromHeading(enSlice, /^#### ❌ Forbidden.*$/m, '^#### |^### |^## ')
  const forbiddenRows = parseMdTable(findFirstTable(forbiddenSlice))
  const forbidden = {}
  for (const row of forbiddenRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    const cat = row[keys[0]]; const words = row[keys[1]]; const reason = row[keys[2]]
    if (cat && cat !== 'Category' && words) {
      forbidden[cat] = { words: splitCommaPreserveParens(words), reason: reason || '' }
    }
  }

  // #### ⚠️ Context-sensitive
  const ctxSlice = sliceFromHeading(enSlice, /^#### ⚠️ Context-sensitive.*$/m, '^#### |^### |^## ')
  const ctxRows = parseMdTable(findFirstTable(ctxSlice))
  const contextSensitive = []
  for (const row of ctxRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    const word = row[keys[0]]; const safe = row[keys[1]]; const dangerous = row[keys[2]]
    if (word && word !== 'Word') contextSensitive.push({ word, safe, dangerous })
  }

  return { allowed, forbidden, contextSensitive }
}

// ─── 5. MIB Lexicon ───

function extractMibLexicon() {
  // Signal-word dictionary
  const dictSlice = sliceFromHeading(doc, /^### MIB 信号词词典.*$/m, '^### |^## ')
  const dictRows = parseMdTable(findFirstTable(dictSlice))
  const signal = []
  for (const row of dictRows) {
    const keys = Object.keys(row)
    if (keys.length < 3) continue
    const type = row[keys[0]]; const examples = row[keys[1]]; const hint = row[keys[2]]
    if (type && type !== '信号词类型') {
      signal.push({
        type,
        examples: examples.split(/[、，,]/).map(s => s.replace(/^"|"$/g, '').trim()).filter(Boolean),
        hint,
      })
    }
  }

  // Calibration sample (first ``` block under "## MIB 风格校准锚")
  const sampleSec = sliceFromHeading(doc, /^## MIB 风格校准锚.*$/m, '^## ')
  const sampleMatch = sampleSec.match(/```\n([\s\S]*?)\n```/)
  const calibrationSample = sampleMatch ? sampleMatch[1].trim() : ''

  // Implementation rules from "### MIB 风格的实施铁律"
  const ruleSlice = sliceFromHeading(doc, /^### MIB 风格的实施铁律.*$/m, '^### |^## ')
  const rules = ruleSlice.split('\n')
    .filter(l => /^\s*-\s+(✅|❌)/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())

  return {
    signal,
    rules,
    calibration_sample: calibrationSample,
    density_rule: '每段 flavor 都暗示水底，但永远不下水。',
  }
}

// ─── 6. Quotas (留白机构 + 上游母题) ───

function extractQuotas() {
  const sectionQuotaSlice = sliceFromHeading(doc, /^## 留白机构使用配额.*$/m, '^## ')
  const upstreamQuotaSlice = sliceFromHeading(doc, /^## 上游母题密度配额.*$/m, '^## ')

  const sectionAlternatives = sectionQuotaSlice.split('\n')
    .filter(l => /^\s*-\s+(?!\*\*)/.test(l) && !/≤|≥|%/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())
    .filter(Boolean)

  const upstreamAlternatives = upstreamQuotaSlice.split('\n')
    .filter(l => /^\s*-\s+(?!\*\*)/.test(l) && !/≤|≥|%/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())
    .filter(Boolean)

  return {
    section_ref_max_pct: 30,
    section_alternatives: sectionAlternatives,
    upstream_motif_max_pct: 40,
    upstream_alternatives: upstreamAlternatives,
    monkey_motif_max_pct: 30,    // Rule 9
    announcement_carrier_max_pct: 40, // Rule 10
  }
}

// ─── Generate ───

function generate() {
  console.log('提取数据从 docs/narrative-design.md (v3.0) ...\n')

  // 1. Anchor facts
  const anchors = extractAnchorFacts()
  console.log(`  锚点: ${Object.keys(anchors).length} 个 (${Object.keys(anchors).join(', ')})`)
  writeFileSync(join(OUT_DIR, 'anchor-facts.mjs'), HEADER + `
export const ANCHOR_FACTS = ${JSON.stringify(anchors, null, 2)}
`)

  // 2. Translation table
  const translations = extractTranslationTable()
  console.log(`  翻译条目: ${translations.length} 条`)
  writeFileSync(join(OUT_DIR, 'translation-table.mjs'), HEADER + `
export const TRANSLATION_TABLE = ${JSON.stringify(translations, null, 2)}

// Quick lookup: game term → narrative term (zh)
export const TERM_ZH = Object.fromEntries(
  TRANSLATION_TABLE.map(e => [e.game, e.zh])
)

// Quick lookup: game term → narrative term (en, may be empty)
export const TERM_EN = Object.fromEntries(
  TRANSLATION_TABLE.map(e => [e.game, e.en])
)
`)

  // 3. Stage config (replaces layer-config)
  const stages = extractStageConfig()
  console.log(`  Acts: ${stages.acts.length} 行  /  Cycles: ${stages.cycles.length} 行`)
  writeFileSync(join(OUT_DIR, 'stage-config.mjs'), HEADER + `
export const STAGE_CONFIG = ${JSON.stringify(stages, null, 2)}
`)

  // 4. B1.a vocab (new)
  const b1a = extractB1aVocab()
  const allowedZhCount = Object.values(b1a.zh.allowed).reduce((n, arr) => n + arr.length, 0)
  const forbiddenZhCount = Object.values(b1a.zh.forbidden).reduce((n, o) => n + o.words.length, 0)
  console.log(`  B1.a vocab: zh allowed=${allowedZhCount} forbidden=${forbiddenZhCount} ctx=${b1a.zh.contextSensitive.length} | en allowed=${Object.values(b1a.en.allowed).reduce((n, arr) => n + arr.length, 0)} forbidden=${Object.values(b1a.en.forbidden).reduce((n, o) => n + o.words.length, 0)} ctx=${b1a.en.contextSensitive.length}`)
  writeFileSync(join(OUT_DIR, 'b1a-vocab.mjs'), HEADER + `
// B1.a 词汇表 — "力量被分发，不被探索" 的明文落地（中 + 英）
export const B1A_VOCAB = ${JSON.stringify(b1a, null, 2)}

// 扁平禁止词清单（含分类原因），便于 validator 快速 lookup
export const FORBIDDEN_ZH = Object.entries(B1A_VOCAB.zh.forbidden).flatMap(([cat, info]) =>
  info.words.map(w => ({ word: w.replace(/（.*?）/g, '').trim(), category: cat, reason: info.reason }))
)

export const FORBIDDEN_EN = Object.entries(B1A_VOCAB.en.forbidden).flatMap(([cat, info]) =>
  info.words.map(w => ({ word: w.replace(/\\(.*?\\)/g, '').trim(), category: cat, reason: info.reason }))
)
`)

  // 5. MIB lexicon (new)
  const mib = extractMibLexicon()
  console.log(`  MIB lexicon: signal=${mib.signal.length} rules=${mib.rules.length} sample=${mib.calibration_sample ? '✓' : '✗'}`)
  writeFileSync(join(OUT_DIR, 'mib-lexicon.mjs'), HEADER + `
// MIB 风格校准 — 信号词词典 + 实施铁律 + calibration sample
export const MIB_LEXICON = ${JSON.stringify(mib, null, 2)}
`)

  // 6. Quotas (new)
  const quotas = extractQuotas()
  console.log(`  Quotas: section ≤${quotas.section_ref_max_pct}% (${quotas.section_alternatives.length} alts) | upstream ≤${quotas.upstream_motif_max_pct}% (${quotas.upstream_alternatives.length} alts)`)
  writeFileSync(join(OUT_DIR, 'quotas.mjs'), HEADER + `
// 内容多样性配额（来自 Self-Consistency 发现 + Creator Discipline Rule 9 / 10）
export const QUOTAS = ${JSON.stringify(quotas, null, 2)}
`)

  console.log(`\n✅ 生成完成`)
  console.log(`   → scripts/narrative-writer/generated/`)
  console.log('     anchor-facts.mjs')
  console.log('     translation-table.mjs')
  console.log('     stage-config.mjs')
  console.log('     b1a-vocab.mjs')
  console.log('     mib-lexicon.mjs')
  console.log('     quotas.mjs')
  console.log(`\n⚠️  v2.3 残留：aigc-art/generated/layer-visual.yaml 不再生成（v3 无 12 层塔）。`)
  console.log(`    旧文件保留为遗留产物；如美术流水线需要 v3 visual 数据，需另立 schema。`)
}

