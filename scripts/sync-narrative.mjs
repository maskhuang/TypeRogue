// ─── 10. Handbooks Validator (v3.1 NEW) ───
// 验证 handbooks-skeleton 数据完整性：rule ID 唯一 / overrides 引用有效 / silent_expirations 引用有效

function validateHandbooks(hb) {
  const errors = []
  const ruleIds = new Set(Object.keys(hb.rules))

  // 1. 每条规则的 version 字段必须匹配它在哪个 versions[].rules 数组里
  for (const [versionKey, version] of Object.entries(hb.versions)) {
    for (const ruleId of version.rules) {
      if (!ruleIds.has(ruleId)) {
        errors.push(`版本 ${versionKey} 引用未定义规则: ${ruleId}`)
        continue
      }
      const rule = hb.rules[ruleId]
      if (rule.version !== versionKey) {
        errors.push(`规则 ${ruleId}.version (${rule.version}) 与版本 ${versionKey} 不一致`)
      }
    }
    // silent_expirations 引用的规则必须存在
    for (const expiredId of (version.silent_expirations || [])) {
      if (!ruleIds.has(expiredId)) {
        errors.push(`版本 ${versionKey}.silent_expirations 引用未定义规则: ${expiredId}`)
      }
    }
  }

  // 2. overrides 引用有效
  for (const [ruleId, rule] of Object.entries(hb.rules)) {
    for (const ov of (rule.overrides || [])) {
      if (!ruleIds.has(ov.rule_id)) {
        errors.push(`规则 ${ruleId}.overrides 引用未定义规则: ${ov.rule_id}`)
      }
    }
    for (const refId of (rule.references || [])) {
      if (!ruleIds.has(refId)) {
        errors.push(`规则 ${ruleId}.references 引用未定义规则: ${refId}`)
      }
    }
  }

  // 3. forms registry 反向校验：mentioned_in 必须对应有 forms_referenced
  for (const [formId, form] of Object.entries(hb.forms)) {
    for (const ruleId of (form.mentioned_in || [])) {
      if (!ruleIds.has(ruleId)) {
        errors.push(`表单 ${formId}.mentioned_in 引用未定义规则: ${ruleId}`)
        continue
      }
      const rule = hb.rules[ruleId]
      if (!(rule.forms_referenced || []).includes(formId)) {
        errors.push(`表单 ${formId} 声称在 ${ruleId} 中提及，但 ${ruleId}.forms_referenced 未列出`)
      }
    }
  }

  // 4. Q4 矛盾密度检查（温和: 每 tier 2-3 expirations）
  for (const [versionKey, version] of Object.entries(hb.versions)) {
    if (versionKey === 'V-1') continue // 基底无 expiration
    const silent = (version.silent_expirations || []).length
    const explicit = version.rules.reduce((n, ruleId) => {
      return n + (hb.rules[ruleId].overrides || []).filter(ov => ov.mode === 'modify' || ov.mode === 'expire').length
    }, 0)
    const total = silent + explicit
    if (total < 2 || total > 4) {
      errors.push(`版本 ${versionKey} expiration 数 (${total} = ${explicit} explicit + ${silent} silent) 超出 Q4 温和范围 [2-3]`)
    }
  }

  return { errors }
}

// ─── 9. Relic Departments (v3.1 NEW) — 11 subsystems → 11 issuing departments ───

function extractRelicDepartments() {
  const sec = sliceFromHeading(
    doc,
    /^## 🟢 Step 5\.5 \(v3\.1 NEW\) · 遗物分发部门体系.*$/m,
    '^## '
  )

  // 11 子系统 → 11 部门 table
  const mappingSlice = sliceFromHeading(sec, /^### 11 子系统 → 11 部门.*$/m, '^### |^## ')
  const mappingTable = findFirstTable(mappingSlice)
  const subsystems = []
  if (mappingTable) {
    for (const row of parseMdTable(mappingTable)) {
      const keys = Object.keys(row)
      if (keys.length < 4) continue
      const subsystem = row[keys[0]]; const examples = row[keys[1]]; const department = row[keys[2]]; const tone = row[keys[3]]
      if (subsystem && subsystem !== '子系统') {
        subsystems.push({
          subsystem: stripBold(subsystem).replace(/^\*+|\*+$/g, '').trim(),
          examples: (examples || '').split(/\s*\/\s*/).map(s => s.trim()).filter(Boolean),
          department: stripBold(department).replace(/^\*+|\*+$/g, '').trim(),
          tone: tone || '',
        })
      }
    }
  }

  // 部门腔调差分 table
  const toneSlice = sliceFromHeading(sec, /^### 部门腔调差分.*$/m, '^### |^## ')
  const toneTable = findFirstTable(toneSlice)
  const department_voice = []
  if (toneTable) {
    for (const row of parseMdTable(toneTable)) {
      const keys = Object.keys(row)
      if (keys.length < 3) continue
      const department = row[keys[0]]; const tone_points = row[keys[1]]; const sample = row[keys[2]]
      if (department && department !== '部门') {
        department_voice.push({
          department: department.replace(/^\*+|\*+$/g, '').trim(),
          tone_points,
          sample: (sample || '').replace(/^"|"$/g, ''),
        })
      }
    }
  }

  return {
    subsystems,
    department_voice,
    quotas: {
      department_max_pct: 25,
      note: '每个部门在 11 部门池中的占比 ≤ 25%（避免单一部门垄断 voice）',
    },
    cleanup_note: 'v3.1 启动后必须批量重写 58/95 v2.3 残留 relic narrative 通过 narrative-writer 流水线产出',
  }
}

// ─── 6. Quotas (留白机构 + 上游母题) ───

function extractQuotas() {
  const sectionQuotaSlice = sliceFromHeading(doc, /^## 留白机构使用配额.*$/m, '^## ')
  const upstreamQuotaSlice = sliceFromHeading(doc, /^## 上游母题密度配额.*$/m, '^## ')

  const sectionAlternatives = sectionQuotaSlice.split('\n')
    .filter(l => /^\s*-\s+(?!\*\*)/.test(l) && !/≤|≥|%/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())
    .filter(Boolean)

  const upstreamAlternatives = upstreamQuotaSlice.split('\n')
    .filter(l => /^\s*-\s+(?!\*\*)/.test(l) && !/≤|≥|%/.test(l))
    .map(l => l.replace(/^\s*-\s+/, '').trim())
    .filter(Boolean)

  return {
    section_ref_max_pct: 30,
    section_alternatives: sectionAlternatives,
    upstream_motif_max_pct: 40,
    upstream_alternatives: upstreamAlternatives,
    monkey_motif_max_pct: 30,    // Rule 9
    announcement_carrier_max_pct: 40, // Rule 10
  }
}

