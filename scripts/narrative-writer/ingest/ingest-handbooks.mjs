// 注：本脚本目前 consume Phase C **手写种子**。Phase E LLM 跑批后，pipeline output
// 中的 handbook entries 会替换 / 增补这些种子。

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

import { POSITION_DENIAL_AFFIRMATION_PAIRS } from '../generated/position-denial-affirmation.mjs'
import { REDACTION_VERSIONED_RULES } from '../generated/redaction-versioning.mjs'
import { validateFragmentV41 } from '../validators/index.mjs'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const PROJECT_ROOT = join(__dirname, '..', '..', '..')
const TARGET_FILE = join(PROJECT_ROOT, 'src', 'src', 'data', 'narrative', 'handbooks.ts')

function parseArgs() {
  return {
    dryRun: process.argv.includes('--dry-run'),
    check: process.argv.includes('--check'),
  }
}

function generateTSContent() {
  const pairsJson = JSON.stringify(POSITION_DENIAL_AFFIRMATION_PAIRS, null, 2)
  const versionedJson = JSON.stringify(REDACTION_VERSIONED_RULES, null, 2)
  const generatedAt = new Date().toISOString().split('T')[0]
  return `// AUTO-GENERATED by scripts/narrative-writer/ingest/ingest-handbooks.mjs
// Source: scripts/narrative-writer/generated/{position-denial-affirmation,redaction-versioning}.mjs
// Last regen: ${generatedAt}
// DO NOT EDIT BY HAND — re-run ingest script to refresh.
//
// 与 narrative-design.md v4.1 §4.1 / §6.3.5 / §6.7 对齐。
// 与 narrative-pipeline-v41-spec §4.1 / §4.3 LOCKED 对齐。
//
// Runtime consumers (待 PL-2/3 实施时接入)：
//   - ClassPicker.ts: 用 PAIR_BY_POSITION 取 denial/affirmation L1 节录
//   - HandbookUI: 用 RULE_BY_ID + resolveActiveVersion 显示当前 cycle 的有效 entry

// ─── Layered footnote types ───

export interface LayeredEntry {
  text_zh: string
  text_en: string
  anomaly_signal_density: number  // 0-1
}

// L3/L4 在 denial state 必须 null
export interface LayeredFragmentDenial {
  L1_recorder: LayeredEntry
  L2_proofreader: LayeredEntry | null
  L3_reviser: null
  L4_author: null
}

// affirmation state · 4 layer 全 populated
export interface LayeredFragmentAffirmation {
  L1_recorder: LayeredEntry
  L2_proofreader: LayeredEntry
  L3_reviser: LayeredEntry
  L4_author: LayeredEntry
}

export type Position = 'recorder' | 'proofreader' | 'reviser' | 'author' | 'assimilated'

export type TransitionMarker = 'silent_affirmation' | 'silent_disappearance'

// ─── Position Denial → Affirmation Flip · §4.1 ───

export interface PositionDenialAffirmationPair {
  id: string
  voice: 'V5_pair'
  section_ref: string
  references_position: Position
  valid_from_chapter: number
  transition_marker: TransitionMarker
  denial: LayeredFragmentDenial
  // §144 (assimilated) affirmation = null（V5 完全退场）
  affirmation: LayeredFragmentAffirmation | null
}

export const POSITION_DENIAL_AFFIRMATION_PAIRS: PositionDenialAffirmationPair[] = ${pairsJson}

export const PAIR_BY_SECTION: Record<string, PositionDenialAffirmationPair> = Object.fromEntries(
  POSITION_DENIAL_AFFIRMATION_PAIRS.map(p => [p.section_ref, p])
)

export const PAIR_BY_POSITION: Partial<Record<Position, PositionDenialAffirmationPair>> = Object.fromEntries(
  POSITION_DENIAL_AFFIRMATION_PAIRS.map(p => [p.references_position, p])
)

/**
 * 给定章节状态返回该 § 号当前应显示的 layered fragment。
 * Used by ClassPicker.ts / handbook UI.
 *
 * §144 (assimilated) Ch.5+ 返回 null（V5 完全退场）。
 */
export function resolveLayeredForSection(
  sectionRef: string,
  chapterState: { current_chapter: number },
): LayeredFragmentDenial | LayeredFragmentAffirmation | null {
  const pair = PAIR_BY_SECTION[sectionRef]
  if (!pair) return null
  const useAffirmation = chapterState.current_chapter >= pair.valid_from_chapter
  if (useAffirmation && pair.affirmation === null) return null  // V5 退场
  return useAffirmation ? pair.affirmation : pair.denial
}

// ─── Versioned Rule (silent修订 · §4.3) ───

export type RedactionMarker =
  | 'silent_amendment'
  | 'silent_addition'
  | 'silent_truncation'
  | 'silent_replacement'
  | 'silent_deletion'
  | null

export interface VersionedRuleEntry {
  version: number
  valid_from_cycle: number
  valid_to_cycle: number | null
  L1_recorder: LayeredEntry
  redaction_marker: RedactionMarker
}

export interface VersionedRule {
  id: string
  section_ref: string
  voice: 'V5'
  versions: VersionedRuleEntry[]
}

export const REDACTION_VERSIONED_RULES: VersionedRule[] = ${versionedJson}

export const RULE_BY_ID: Record<string, VersionedRule> = Object.fromEntries(
  REDACTION_VERSIONED_RULES.map(r => [r.id, r])
)

/**
 * 给定 rule_id + current_cycle 返回当前有效 version。
 */
export function resolveActiveVersion(ruleId: string, currentCycle: number): VersionedRuleEntry | null {
  const rule = RULE_BY_ID[ruleId]
  if (!rule) return null
  return rule.versions.find(v =>
    currentCycle >= v.valid_from_cycle &&
    (v.valid_to_cycle === null || currentCycle <= v.valid_to_cycle)
  ) ?? null
}
`
}

// ─── validators check ───

function runValidators() {
  console.log('━'.repeat(60))
  console.log('  Validators check')
  console.log('━'.repeat(60))
  let totalErrors = 0
  for (const pair of POSITION_DENIAL_AFFIRMATION_PAIRS) {
    const result = validateFragmentV41(pair, 'V5_pair', { context: 'narrative_flavor' })
    if (!result.passed) {
      console.log(`  ✗ ${pair.section_ref} · ${result.errors.length} error(s):`)
      for (const e of result.errors) console.log(`      ${e}`)
      totalErrors += result.errors.length
    } else {
      console.log(`  ✓ ${pair.section_ref}`)
    }
  }
  for (const rule of REDACTION_VERSIONED_RULES) {
    for (const ver of rule.versions) {
      const fakeFragment = {
        L1_recorder: ver.L1_recorder,
        L2_proofreader: null,
        L3_reviser: null,
        L4_author: null,
      }
      const result = validateFragmentV41(fakeFragment, 'V5', { context: 'narrative_flavor' })
      if (!result.passed) {
        console.log(`  ✗ ${rule.section_ref} v${ver.version} · ${result.errors.length} error(s):`)
        for (const e of result.errors) console.log(`      ${e}`)
        totalErrors += result.errors.length
      } else {
        console.log(`  ✓ ${rule.section_ref} v${ver.version}`)
      }
    }
  }
  return totalErrors
}

// ─── Main ───

async function main() {
  const opts = parseArgs()

  console.log('╔' + '═'.repeat(58) + '╗')
  console.log('║   ingest-handbooks · Phase E ingest                      ║')
  console.log('╚' + '═'.repeat(58) + '╝')
  console.log()
  console.log(`  Source: position-denial-affirmation (${POSITION_DENIAL_AFFIRMATION_PAIRS.length} pairs) + redaction-versioning (${REDACTION_VERSIONED_RULES.length} rules · ${REDACTION_VERSIONED_RULES.reduce((sum, r) => sum + r.versions.length, 0)} versions)`)
  console.log(`  Target: ${TARGET_FILE}`)
  console.log()

  if (opts.check) {
    const errors = runValidators()
    if (errors > 0) {
      console.error(`\n  ❌ ${errors} validator error(s) — ingest aborted`)
      process.exit(1)
    }
    console.log('\n  ✅ All validators pass')
    return
  }

  const errors = runValidators()
  if (errors > 0) {
    console.error(`\n  ❌ ${errors} validator error(s) — ingest aborted`)
    process.exit(1)
  }

  const tsContent = generateTSContent()

  if (opts.dryRun) {
    console.log()
    console.log('━'.repeat(60))
    console.log('  [DRY RUN] Would write:')
    console.log('━'.repeat(60))
    console.log(`  ${TARGET_FILE}`)
    console.log(`  ${tsContent.length} chars / ${tsContent.split('\n').length} lines`)
    console.log()
    console.log('  Existing file:', existsSync(TARGET_FILE) ? '会覆盖' : '会新建')
    return
  }

  // 实际写入
  const targetDir = dirname(TARGET_FILE)
  if (!existsSync(targetDir)) mkdirSync(targetDir, { recursive: true })
  writeFileSync(TARGET_FILE, tsContent, 'utf-8')

  console.log(`\n  ✅ 已写入: ${TARGET_FILE}`)
  console.log(`     ${tsContent.length} chars / ${tsContent.split('\n').length} lines`)
}

main().catch(err => {
  console.error('错误:', err)
  process.exit(1)
})
