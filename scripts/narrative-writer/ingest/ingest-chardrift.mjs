#!/usr/bin/env node
//
// ingest-chardrift.mjs (Phase E / spec §6.2)
//
// Reads:  generated/char-drift-patterns.mjs · CHAR_DRIFT_PATTERNS (10 V3 patterns)
// Writes: src/src/data/narrative/charDrift.ts (NEW · 低风险 · 还无 game UI consumer)
//
// Runtime consumer (待 PL-11 实施时接入):
//   - CharDriftEffect.ts: hover / cycle_end / cycle_start trigger 时启用 stages 序列
//
// CLI: --dry-run · --check

import { writeFileSync, mkdirSync, existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

import { CHAR_DRIFT_PATTERNS } from '../generated/char-drift-patterns.mjs'
import { validateFragmentV41 } from '../validators/index.mjs'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const PROJECT_ROOT = join(__dirname, '..', '..', '..')
const TARGET_FILE = join(PROJECT_ROOT, 'src', 'src', 'data', 'narrative', 'charDrift.ts')

function parseArgs() {
  return {
    dryRun: process.argv.includes('--dry-run'),
    check: process.argv.includes('--check'),
  }
}

function generateTSContent() {
  const patternsJson = JSON.stringify(CHAR_DRIFT_PATTERNS, null, 2)
  const generatedAt = new Date().toISOString().split('T')[0]
  return `// AUTO-GENERATED by scripts/narrative-writer/ingest/ingest-chardrift.mjs
// Source: scripts/narrative-writer/generated/char-drift-patterns.mjs
// Last regen: ${generatedAt}
// DO NOT EDIT BY HAND — re-run ingest script to refresh.
//
// 与 narrative-design.md v4.1 §6.3.3 + memory feedback_ui_label_vocabulary.md 对齐。
// Cycle 6+ Endless 启用单字符级缓变作为污染症候。

export type DriftEvent = 'hover' | 'cycle_end' | 'cycle_start'

export interface DriftTrigger {
  cycle_gte: number  // 触发的最小 cycle（一般是 6 = Endless）
  event: DriftEvent
  target_selector?: string  // hover 模式下的 DOM selector
  probability?: number  // 0-1，仅 cycle_end / cycle_start 模式用
}

export interface CharDriftPattern {
  id: string
  voice: 'V3'
  trigger: DriftTrigger
  stages: string[]  // 文本序列；按 duration_ms 顺序展示
  duration_ms: number
  settle_on_mouse_leave: boolean
  description: string
}

export const CHAR_DRIFT_PATTERNS: CharDriftPattern[] = ${patternsJson}

export const PATTERN_BY_ID: Record<string, CharDriftPattern> = Object.fromEntries(
  CHAR_DRIFT_PATTERNS.map(p => [p.id, p])
)

/** 按事件类型 + 当前 cycle filter pattern · runtime CharDriftEffect 用 */
export function getPatternsForEvent(event: DriftEvent, cycle: number): CharDriftPattern[] {
  return CHAR_DRIFT_PATTERNS.filter(p =>
    p.trigger.event === event &&
    cycle >= (p.trigger.cycle_gte || 1)
  )
}

/** 按 DOM selector + cycle filter hover pattern */
export function getPatternsForTarget(selector: string, cycle: number): CharDriftPattern[] {
  return CHAR_DRIFT_PATTERNS.filter(p =>
    p.trigger.event === 'hover' &&
    p.trigger.target_selector === selector &&
    cycle >= (p.trigger.cycle_gte || 1)
  )
}
`
}

function runValidators() {
  console.log('━'.repeat(60))
  console.log('  Validators check')
  console.log('━'.repeat(60))
  let totalErrors = 0
  for (const pat of CHAR_DRIFT_PATTERNS) {
    const fakeFragment = {
      fragment_zh: pat.stages[0] || '',
      fragment_en: '',
      drift_pattern: pat.stages,
      readability: 'self_consistent_but_alien',
    }
    const result = validateFragmentV41(fakeFragment, 'V3', { context: 'narrative_flavor' })
    if (!result.passed) {
      console.log(`  ✗ ${pat.id} · ${result.errors.length} error(s):`)
      for (const e of result.errors) console.log(`      ${e}`)
      totalErrors += result.errors.length
    } else {
      console.log(`  ✓ ${pat.id}`)
    }
  }
  return totalErrors
}

async function main() {
  const opts = parseArgs()

  console.log('╔' + '═'.repeat(58) + '╗')
  console.log('║   ingest-chardrift · Phase E ingest                      ║')
  console.log('╚' + '═'.repeat(58) + '╝')
  console.log()
  console.log(`  Source: char-drift-patterns (${CHAR_DRIFT_PATTERNS.length} patterns)`)
  console.log(`  Target: ${TARGET_FILE}`)
  console.log()

  if (opts.check) {
    const errors = runValidators()
    if (errors > 0) { console.error(`\n  ❌ ${errors} validator error(s) — ingest aborted`); process.exit(1) }
    console.log('\n  ✅ All validators pass'); return
  }

  const errors = runValidators()
  if (errors > 0) { console.error(`\n  ❌ ${errors} validator error(s)`); process.exit(1) }

  const tsContent = generateTSContent()

  if (opts.dryRun) {
    console.log()
    console.log('━'.repeat(60))
    console.log('  [DRY RUN] Would write:')
    console.log('━'.repeat(60))
    console.log(`  ${TARGET_FILE}`)
    console.log(`  ${tsContent.length} chars / ${tsContent.split('\n').length} lines`)
    console.log(`  Existing file: ${existsSync(TARGET_FILE) ? '会覆盖' : '会新建'}`)
    return
  }

  const targetDir = dirname(TARGET_FILE)
  if (!existsSync(targetDir)) mkdirSync(targetDir, { recursive: true })
  writeFileSync(TARGET_FILE, tsContent, 'utf-8')

  console.log(`\n  ✅ 已写入: ${TARGET_FILE}`)
  console.log(`     ${tsContent.length} chars / ${tsContent.split('\n').length} lines`)
}

main().catch(err => { console.error('错误:', err); process.exit(1) })
