// Build a batch prompt for multiple objects of the same type+voice
export function buildBatchPrompt(objects, type, voice, template) {
  const templateGuide = TEMPLATE_GUIDES[template] || ''
  const objList = objects.map((o, i) => `[${i + 1}] ${summarizeObject(o, type)}`).join('\n')

  if (voice === 'bell') {
    return `为以下 ${objects.length} 个游戏对象批量生成 🔔 教会声音 flavor text。

## 对象列表
${objList}

## 模板：${template}
${templateGuide}

## 输出格式
输出一个 JSON 数组，每个元素：
{
  "id": "对象ID",
  "name_zh": "中文叙事名",
  "name_en": "English Narrative Name",
  "text_zh": "中文 flavor（≤60字）",
  "text_en": "English flavor (≤25 words)"
}

${ANTI_LEAK}

请直接输出 JSON 数组，不要包含 markdown 代码块标记。`
  }

  if (voice === 'doc') {
    return `为以下 ${objects.length} 个游戏对象批量生成 📄 档案声音 Codex 条目。

## 对象列表
${objList}

## 模板：${template}
${templateGuide}

## 输出格式
输出一个 JSON 数组，每个元素：
{
  "id": "对象ID",
  "text_zh": "中文档案条目（≤8行）",
  "text_en": "English archive entry (≤8 lines)"
}

${ANTI_LEAK}

请直接输出 JSON 数组，不要包含 markdown 代码块标记。`
  }

  // Fallback: single-item generation for other voices
  return buildUserPrompt(objects[0], type, voice, template)
}

