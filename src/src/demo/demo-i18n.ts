// === 核心 t() 函数 ===
export function t(key: string, params?: Record<string, string | number>): string {
  const dict = currentLocale === 'en' ? EN : ZH
  let str = dict[key]
  if (str === undefined) {
    // fallback: ZH dict, then raw key
    str = ZH[key] ?? key
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, String(v))
    }
  }
  return str
}

// === DOM 扫描替换 ===
// 默认用 textContent；元素带 data-i18n-html attribute 时用 innerHTML（用于内含 <br> 等的多行值）
// 输入框可用 data-i18n-placeholder="key" 单独翻译 placeholder
export function applyHtmlI18n(): void {
  document.documentElement.lang = currentLocale === 'zh' ? 'zh-CN' : 'en'
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = (el as HTMLElement).dataset.i18n!
    if ((el as HTMLElement).hasAttribute('data-i18n-html')) {
      el.innerHTML = t(key)
    } else {
      el.textContent = t(key)
    }
  })
  document.querySelectorAll<HTMLInputElement>('input[data-i18n-placeholder]').forEach(input => {
    const key = input.dataset.i18nPlaceholder!
    input.placeholder = t(key)
  })
}

// === 物品名/描述翻译 ===
export function localizeItemName(id: string, zhName: string): string {
  if (currentLocale === 'zh') return zhName
  return ITEM_NAMES_EN[id] ?? zhName
}

export function localizeItemDesc(id: string, zhDesc: string): string {
  if (currentLocale === 'zh') return zhDesc
  return ITEM_DESCS_EN[id] ?? zhDesc
}

export function localizeItemFlavor(id: string, zhFlavor: string | undefined): string {
  if (!zhFlavor) return ''
  if (currentLocale === 'zh') return zhFlavor
  return ITEM_FLAVORS_EN[id] ?? ''
}

